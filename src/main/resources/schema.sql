-- Mismo esquema para PostgreSQL (docker compose) y H2 (desarrollo y tests).

CREATE TABLE IF NOT EXISTS uploads (
    id               UUID PRIMARY KEY,
    file_name        VARCHAR(255)  NOT NULL,
    storage_key      VARCHAR(300)  NOT NULL,
    idempotency_key  VARCHAR(200)  NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    processed_rows   INT           NOT NULL DEFAULT 0,
    error_rows       INT           NOT NULL DEFAULT 0,
    failure_reason   VARCHAR(1000),
    uploaded_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_uploads_idempotency_key UNIQUE (idempotency_key)
);
CREATE INDEX IF NOT EXISTS ix_uploads_uploaded_at ON uploads (uploaded_at);
CREATE INDEX IF NOT EXISTS ix_uploads_status ON uploads (status);

CREATE TABLE IF NOT EXISTS activity_data (
    id             UUID PRIMARY KEY,
    upload_id      UUID          NOT NULL REFERENCES uploads (id),
    line_number    INT           NOT NULL,
    category       VARCHAR(200)  NOT NULL,
    amount         NUMERIC(18, 4) NOT NULL,
    unit           VARCHAR(50)   NOT NULL,
    activity_date  DATE          NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_activity_upload ON activity_data (upload_id, line_number);
CREATE INDEX IF NOT EXISTS ix_activity_date ON activity_data (activity_date);

CREATE TABLE IF NOT EXISTS row_errors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id    UUID          NOT NULL REFERENCES uploads (id),
    line_number  INT           NOT NULL,
    message      VARCHAR(1000) NOT NULL,
    raw_line     VARCHAR(400)
);
CREATE INDEX IF NOT EXISTS ix_row_errors_upload ON row_errors (upload_id, line_number);

-- Cola de mensajes con la semantica de SQS: visibility timeout, contador de recepciones y DLQ.
-- Vive en la misma base que los uploads, asi que encolar es parte de la misma transaccion (outbox).
CREATE TABLE IF NOT EXISTS queue_messages (
    id             UUID PRIMARY KEY,
    upload_id      UUID          NOT NULL,
    status         VARCHAR(20)   NOT NULL,          -- QUEUED, DONE, DEAD, REDRIVEN
    receive_count  INT           NOT NULL DEFAULT 0,
    visible_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error     VARCHAR(1000)
);
CREATE INDEX IF NOT EXISTS ix_queue_ready ON queue_messages (status, visible_at);
